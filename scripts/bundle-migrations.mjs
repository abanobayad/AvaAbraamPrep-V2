// Embeds prisma/migrations/*/migration.sql into src/lib/migrations.generated.ts so the
// running app can apply migrations without reading the filesystem (runs before `next build`).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const dir = path.resolve("prisma", "migrations");
const names = existsSync(dir)
  ? readdirSync(dir).filter((n) => existsSync(path.join(dir, n, "migration.sql"))).sort()
  : [];
const migrations = names.map((name) => ({ name, sql: readFileSync(path.join(dir, name, "migration.sql"), "utf8") }));
const out = `// GENERATED by scripts/bundle-migrations.mjs. Do not edit; edit prisma/migrations instead.
export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(path.resolve("src", "lib", "migrations.generated.ts"), out);
console.log(`bundled ${migrations.length} migration(s): ${names.join(", ")}`);
